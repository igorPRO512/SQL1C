def build_module_xml(src: str, name_new: str) -> str:
    text = rename_code(src)
    det_uuid = str(uuid.uuid5(UUID_NS, name_new))
    text = re.sub(r'uuid="[0-9a-fA-F-]{36}"', f'uuid="{det_uuid}"', text, count=1)
    return text


def register_in_configuration(cfg: Path, names, dry_run: bool) -> list:
    raw = cfg.read_bytes()
    bom = raw.startswith(BOM)
    text = raw[len(BOM):].decode("utf-8") if bom else raw.decode("utf-8")
    nl = "\r\n" if "\r\n" in text else "\n"

    idx = text.rfind("</ChildObjects>")
    if idx < 0:
        raise SystemExit("В Configuration.xml не найден </ChildObjects>")

    indents = re.findall(r"^([ \t]*)<CommonModule>", text, re.M)
    indent = indents[-1] if indents else "\t\t\t"
    existing = set(re.findall(r"<CommonModule>([^<]+)</CommonModule>", text))
    to_add = [n for n in names if n not in existing]
    if not to_add:
        return []

    add = "".join(f"{indent}<CommonModule>{n}</CommonModule>{nl}" for n in to_add)
    line_start = text.rfind("\n", 0, idx) + 1
    text = text[:line_start] + add + text[line_start:]
    if not dry_run:
        write(cfg, text, bom=bom)
    return to_add


def update_readme(path: Path, text: str, dry_run: bool) -> None:
    if not dry_run:
        write(path, text, bom=False)


