BOM = b"\xef\xbb\xbf"


# ---------------------------------------------------------------- утилиты

def read(path: Path) -> str:
    raw = path.read_bytes()
    if raw.startswith(BOM):
        raw = raw[len(BOM):]
    return raw.decode("utf-8")


def write(path: Path, text: str, bom: bool = True) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = text.encode("utf-8")
    path.write_bytes((BOM if bom else b"") + data)


def new_name(name: str) -> str:
    """OPI_X -> Ext1_OPI_X"""
    return "Ext1_" + name


def rename_code(text: str) -> str:
    """Переименовывает идентификаторы OPI_* в Ext1_OPI_*, не трогая защищённые литералы."""
    slots = {}
    for i, literal in enumerate(PROTECTED):
        if literal in text:
            token = f"\x00{i}\x00"
            text = text.replace(literal, token)
            slots[token] = literal
    text = re.sub(r"\bOPI_(\w+)", r"Ext1_OPI_\1", text)
    for token, literal in slots.items():
        text = text.replace(token, literal)
    return text


def refs(text: str) -> set:
    """Имена модулей OPI_*, на которые ссылается текст (без защищённых литералов)."""
    for literal in PROTECTED:
        text = text.replace(literal, " ")
    return {"OPI_" + m for m in re.findall(r"\bOPI_(\w+)", text)}


def module_bsl(opi: Path, name: str) -> Path:
    return opi / "CommonModules" / name / "Ext" / "Module.bsl"


def module_xml(opi: Path, name: str) -> Path:
    return opi / "CommonModules" / f"{name}.xml"


def collect(opi: Path):
    """Замыкание зависимостей, начиная с коннектора."""
    needed, missing, seen = [], set(), set()
    queue = [CONNECTOR_FULL]
    while queue:
        name = queue.pop(0)
        if name in seen:
            continue
        seen.add(name)
        if not module_bsl(opi, name).exists() or not module_xml(opi, name).exists():
            missing.add(name)
            continue
        needed.append(name)
        queue.extend(sorted(refs(read(module_bsl(opi, name)))))
    return needed, missing


CONNECTOR_FULL = "OPI_" + CONNECTOR[len("OPI_"):]  # OPI_MSSQL


def git(args, cwd):
    return subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)


