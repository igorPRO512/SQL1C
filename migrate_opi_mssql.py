# ---------------------------------------------------------------- main

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--repo", default=".", help="путь к клону репозитория SQL1C (по умолчанию текущая папка)")
    parser.add_argument("--dry-run", action="store_true", help="только показать план, файлы не менять")
    parser.add_argument("--branch", action="store_true", help=f"создать ветку {BRANCH} через git перед изменениями")
    parser.add_argument("--force", action="store_true", help="работать, даже если в 1CSQLSYNCHRONYSATOR есть незакоммиченные изменения")
    args = parser.parse_args()

    root = Path(args.repo).resolve()
    opi = root / OPI_DIR
    tgt = root / TARGET_DIR
    if not (opi / "CommonModules").is_dir():
        print(f"Не найдена папка {OPI_DIR}/CommonModules в {root}")
        return 1
    if not (tgt / "CommonModules").is_dir():
        print(f"Не найдена папка {TARGET_DIR}/CommonModules в {root}")
        return 1
    if not module_bsl(tgt, EXT1_MODULE).exists():
        print(f"Не найден модуль {TARGET_DIR}/CommonModules/{EXT1_MODULE}/Ext/Module.bsl")
        return 1

    # Проверка git: не затирать чужие незакоммиченные правки
    status = git(["status", "--porcelain", "--", TARGET_DIR], root)
    if status.returncode == 0:
        if status.stdout.strip() and not args.force and not args.dry_run:
            print("В папке 1CSQLSYNCHRONYSATOR есть незакоммиченные изменения:")
            print(status.stdout)
            print("Закоммитьте их или запустите с --force.")
            return 1
    else:
        print("Предупреждение: git не найден или это не репозиторий, резервной копии через git не будет.")

    needed, missing = collect(opi)
    print(f"Модулей коннектора к переносу: {len(needed)}")
    for name in needed:
        print(f"  {name} -> {new_name(name)}")
    if missing:
        print("ВНИМАНИЕ: не найдены модули (ссылки из кода есть, файлов нет):")
        for name in sorted(missing):
            print(f"  {name}")
        print("Проверьте, что они действительно нужны; при необходимости перенесите вручную.")

    if args.dry_run:
        print("\n--dry-run: файлы не изменены.")
        return 0

    if args.branch:
        r = git(["checkout", "-b", BRANCH], root)
        if r.returncode != 0:
            print("Не удалось создать ветку:", r.stderr.strip())
            return 1
        print(f"Создана ветка {BRANCH}")

    # 1. Модули коннектора и зависимости
    for name in needed:
        new = new_name(name)
        bsl_src = read(module_bsl(opi, name))
        xml_src = read(module_xml(opi, name))
        write(tgt / "CommonModules" / new / "Ext" / "Module.bsl", rename_code(bsl_src))
        write(tgt / "CommonModules" / f"{new}.xml", build_module_xml(xml_src, new))

    # 2. Переписанный модуль синхронизации
    write(module_bsl(tgt, EXT1_MODULE), EXT1_BSL)

    # 3. Регистрация в Configuration.xml
    added = register_in_configuration(
        tgt / "Configuration.xml",
        [new_name(n) for n in needed],
        dry_run=False,
    )
    print(f"Добавлено в Configuration.xml: {len(added)}")

    # 4. README расширения
    update_readme(tgt / "README.md", README_TEXT, dry_run=False)

    print("\nГотово. Проверьте изменения: git status / git diff.")
    print("Далее: загрузить конфигурацию в конфигуратор, проверить компиляцию, подключить компоненту OPI_MSSQL.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
